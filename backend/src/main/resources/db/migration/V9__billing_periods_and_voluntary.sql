ALTER TABLE households ADD INDEX idx_households_status_id (status, id);

CREATE TABLE billing_periods (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    period CHAR(7) NOT NULL,
    due_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    revision BIGINT NOT NULL DEFAULT 0,
    receipt_count BIGINT NOT NULL DEFAULT 0,
    replaces_period_id BIGINT NULL,
    created_by BIGINT NOT NULL,
    created_at DATETIME(6) NOT NULL,
    submitted_by BIGINT NULL,
    submitted_at DATETIME(6) NULL,
    issued_by BIGINT NULL,
    issued_at DATETIME(6) NULL,
    cancelled_by BIGINT NULL,
    cancelled_at DATETIME(6) NULL,
    return_reason VARCHAR(255) NULL,
    cancel_reason VARCHAR(255) NULL,
    active_month CHAR(7) GENERATED ALWAYS AS (CASE WHEN status <> 'CANCELLED' THEN period ELSE NULL END) STORED,
    UNIQUE KEY uq_billing_period_active_month (active_month),
    KEY idx_billing_period_month_status (period, status),
    CONSTRAINT fk_billing_period_replaces FOREIGN KEY (replaces_period_id) REFERENCES billing_periods (id),
    CONSTRAINT fk_billing_period_creator FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT fk_billing_period_submitter FOREIGN KEY (submitted_by) REFERENCES users (id),
    CONSTRAINT fk_billing_period_issuer FOREIGN KEY (issued_by) REFERENCES users (id),
    CONSTRAINT fk_billing_period_canceller FOREIGN KEY (cancelled_by) REFERENCES users (id),
    CONSTRAINT ck_billing_period_status CHECK (status IN ('DRAFT', 'PENDING_APPROVAL', 'ISSUED', 'CANCELLED')),
    CONSTRAINT ck_billing_period_counters CHECK (version >= 0 AND revision >= 0 AND receipt_count >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE billing_submissions (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    period_id BIGINT NOT NULL,
    revision BIGINT NOT NULL,
    submitted_by BIGINT NOT NULL,
    submitted_at DATETIME(6) NOT NULL,
    household_count BIGINT NOT NULL,
    total DECIMAL(24,0) NOT NULL,
    UNIQUE KEY uq_billing_submission_revision (period_id, revision),
    CONSTRAINT fk_billing_submission_period FOREIGN KEY (period_id) REFERENCES billing_periods (id),
    CONSTRAINT fk_billing_submission_actor FOREIGN KEY (submitted_by) REFERENCES users (id),
    CONSTRAINT ck_billing_submission_total CHECK (household_count > 0 AND total >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE billing_submission_items (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    submission_id BIGINT NOT NULL,
    household_id BIGINT NOT NULL,
    household_code VARCHAR(50) NOT NULL,
    apartment_code VARCHAR(50) NOT NULL,
    area_m2 DECIMAL(10,2) NULL,
    fee_type_id BIGINT NOT NULL,
    fee_type_code VARCHAR(50) NOT NULL,
    fee_type_name VARCHAR(150) NOT NULL,
    calculation_method VARCHAR(20) NOT NULL,
    quantity DECIMAL(10,2) NOT NULL,
    unit_price DECIMAL(12,2) NOT NULL,
    fee_rate_id BIGINT NOT NULL,
    amount DECIMAL(24,0) NOT NULL,
    UNIQUE KEY uq_submission_household_fee (submission_id, household_id, fee_type_id),
    KEY idx_submission_household (submission_id, household_id),
    CONSTRAINT fk_submission_item_submission FOREIGN KEY (submission_id) REFERENCES billing_submissions (id),
    CONSTRAINT fk_submission_item_household FOREIGN KEY (household_id) REFERENCES households (id),
    CONSTRAINT fk_submission_item_type FOREIGN KEY (fee_type_id) REFERENCES fee_types (id),
    CONSTRAINT fk_submission_item_rate FOREIGN KEY (fee_rate_id) REFERENCES fee_rates (id),
    CONSTRAINT ck_submission_item_amount CHECK (quantity > 0 AND unit_price > 0 AND amount >= 0),
    CONSTRAINT ck_submission_item_method CHECK (calculation_method IN ('AREA', 'PER_HOUSEHOLD'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE invoices (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    period_id BIGINT NOT NULL,
    household_id BIGINT NOT NULL,
    household_code VARCHAR(50) NOT NULL,
    apartment_code VARCHAR(50) NOT NULL,
    due_date DATE NOT NULL,
    total DECIMAL(24,0) NOT NULL,
    status VARCHAR(20) NOT NULL,
    issued_at DATETIME(6) NOT NULL,
    cancelled_at DATETIME(6) NULL,
    UNIQUE KEY uq_invoice_period_household (period_id, household_id),
    CONSTRAINT fk_invoice_period FOREIGN KEY (period_id) REFERENCES billing_periods (id),
    CONSTRAINT fk_invoice_household FOREIGN KEY (household_id) REFERENCES households (id),
    CONSTRAINT ck_invoice_status CHECK (status IN ('ISSUED', 'CANCELLED')),
    CONSTRAINT ck_invoice_total CHECK (total >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE invoice_lines (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    invoice_id BIGINT NOT NULL,
    fee_type_id BIGINT NOT NULL,
    fee_type_code VARCHAR(50) NOT NULL,
    fee_type_name VARCHAR(150) NOT NULL,
    calculation_method VARCHAR(20) NOT NULL,
    area_m2 DECIMAL(10,2) NULL,
    quantity DECIMAL(10,2) NOT NULL,
    unit_price DECIMAL(12,2) NOT NULL,
    fee_rate_id BIGINT NOT NULL,
    amount DECIMAL(24,0) NOT NULL,
    UNIQUE KEY uq_invoice_line_fee (invoice_id, fee_type_id),
    CONSTRAINT fk_invoice_line_invoice FOREIGN KEY (invoice_id) REFERENCES invoices (id),
    CONSTRAINT fk_invoice_line_type FOREIGN KEY (fee_type_id) REFERENCES fee_types (id),
    CONSTRAINT fk_invoice_line_rate FOREIGN KEY (fee_rate_id) REFERENCES fee_rates (id),
    CONSTRAINT ck_invoice_line_amount CHECK (quantity > 0 AND unit_price > 0 AND amount >= 0),
    CONSTRAINT ck_invoice_line_method CHECK (calculation_method IN ('AREA', 'PER_HOUSEHOLD'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE voluntary_campaigns (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(2000) NULL,
    opens_on DATE NOT NULL,
    closes_on DATE NOT NULL,
    status VARCHAR(20) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_by BIGINT NOT NULL,
    created_at DATETIME(6) NOT NULL,
    published_by BIGINT NULL,
    published_at DATETIME(6) NULL,
    closed_by BIGINT NULL,
    closed_at DATETIME(6) NULL,
    CONSTRAINT fk_campaign_creator FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT fk_campaign_publisher FOREIGN KEY (published_by) REFERENCES users (id),
    CONSTRAINT fk_campaign_closer FOREIGN KEY (closed_by) REFERENCES users (id),
    CONSTRAINT ck_campaign_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'CLOSED')),
    CONSTRAINT ck_campaign_dates CHECK (closes_on >= opens_on),
    KEY idx_campaign_status_dates (status, opens_on, closes_on)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE voluntary_contributions (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    campaign_id BIGINT NOT NULL,
    resident_id BIGINT NOT NULL,
    household_id BIGINT NOT NULL,
    donor_name_snapshot VARCHAR(150) NOT NULL,
    household_code_snapshot VARCHAR(50) NOT NULL,
    apartment_code_snapshot VARCHAR(50) NOT NULL,
    amount DECIMAL(18,0) NOT NULL,
    paid_on DATE NOT NULL,
    recorded_by BIGINT NOT NULL,
    recorded_at DATETIME(6) NOT NULL,
    status VARCHAR(20) NOT NULL,
    late_reason VARCHAR(255) NULL,
    voided_by BIGINT NULL,
    voided_at DATETIME(6) NULL,
    void_reason VARCHAR(255) NULL,
    version BIGINT NOT NULL DEFAULT 0,
    idempotency_key CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    request_fingerprint CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    UNIQUE KEY uq_contribution_actor_key (recorded_by, idempotency_key),
    KEY idx_contribution_campaign_status_time (campaign_id, status, recorded_at, id),
    CONSTRAINT fk_contribution_campaign FOREIGN KEY (campaign_id) REFERENCES voluntary_campaigns (id),
    CONSTRAINT fk_contribution_resident FOREIGN KEY (resident_id) REFERENCES residents (id),
    CONSTRAINT fk_contribution_household FOREIGN KEY (household_id) REFERENCES households (id),
    CONSTRAINT fk_contribution_actor FOREIGN KEY (recorded_by) REFERENCES users (id),
    CONSTRAINT fk_contribution_voider FOREIGN KEY (voided_by) REFERENCES users (id),
    CONSTRAINT ck_contribution_status CHECK (status IN ('POSTED', 'VOIDED')),
    CONSTRAINT ck_contribution_amount CHECK (amount > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
